const I18nContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
} | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const stored = typeof window !== "undefined" ? localStorage.getItem("fk-lang") : null;
      return (stored as Lang) || "SK";
    } catch {
      return "SK";
    }
  });

  useEffect(() => {
    try {
      localStorage.setItem("fk-lang", lang);
    } catch {}
    if (typeof document !== "undefined") document.documentElement.lang = lang.toLowerCase();
  }, [lang]);

  const t = (key: string) => translations[lang][key] ?? translations.SK[key] ?? key;

  return <I18nContext.Provider value={{ lang, setLang: setLangState, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

export function usePageMeta(titleKey: string, descriptionKey?: string) {
  const { t } = useI18n();

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.title = t(titleKey);
      if (descriptionKey) {
        const content = t(descriptionKey);
        let meta = document.querySelector('meta[name="description"]') as HTMLMetaElement | null;
        if (!meta) {
          meta = document.createElement("meta");
          meta.setAttribute("name", "description");
          document.head.appendChild(meta);
        }
        meta.setAttribute("content", content);
      }
    }
  }, [t, titleKey, descriptionKey]);
}

export default I18nProvider;
